// Vercel build step: writes public/config.js so the website talks to the bot server on Railway.
// Default: https://sigmaxmd.up.railway.app. To use another bot server set SIGMA_API_URL in Vercel -> Settings -> Environment Variables.
const fs = require('fs');
const path = require('path');

const DEFAULT_API = 'https://sigmaxmd.up.railway.app';
const raw = String(process.env.SIGMA_API_URL || DEFAULT_API).trim().replace(/\/+$/, '');
if (!raw) {
  console.warn('[build-config] SIGMA_API_URL is not set. The page will call its own domain, so servers/pairing will not work on Vercel.');
} else if (!/^https:\/\/[^\s"'<>]+$/i.test(raw)) {
  console.error('[build-config] SIGMA_API_URL must be a full https:// URL (no spaces or quotes). Got: ' + raw);
  process.exit(1);
}
const file = path.join(__dirname, '..', 'public', 'config.js');
fs.writeFileSync(file, '// generated by scripts/build-config.js\nwindow.SIGMA_API = ' + JSON.stringify(raw) + ';\n');
console.log('[build-config] API base =', raw || '(same origin)');
